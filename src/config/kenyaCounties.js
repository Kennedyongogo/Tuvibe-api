const sanitize = (value) =>
  value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z]/g, "");

const COUNTY_LOOKUP = RAW_COUNTIES.reduce((acc, name) => {
  acc[sanitize(name)] = name;
  return acc;
}, {});

const normalizeCountyName = (value) => {
  if (typeof value !== "string") return null;
  const cleaned = sanitize(value);
  if (!cleaned) return null;
  return COUNTY_LOOKUP[cleaned] || null;
};

const isValidCounty = (value) => Boolean(normalizeCountyName(value));

module.exports = {
  KENYA_COUNTIES: RAW_COUNTIES,
  normalizeCountyName,
  isValidCounty,
};
